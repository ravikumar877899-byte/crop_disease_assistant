def localize_application_method(method_str: str, lang: str) -> str:
    if not method_str:
        return APPLICATION_METHOD_I18N.get(lang, {}).get('foliar', "Foliar Spray")
    if lang == 'en':
        return method_str
    # If method already has non-ASCII characters (native script), preserve it
    if any(ord(c) > 127 for c in method_str):
        return method_str
    m_lower = method_str.lower()
    lang_dict = APPLICATION_METHOD_I18N.get(lang, APPLICATION_METHOD_I18N['en'])
    for key, val in lang_dict.items():
        if key in m_lower:
            return val
    return lang_dict.get('foliar', method_str)

