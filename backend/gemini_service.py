def evaluate_spraying_window(weather_context: Optional[Dict[str, Any]], language: str = 'en') -> Tuple[str, str]:
    """
    Determines spraying window status ('GOOD SPRAYING WINDOW', 'CAUTION', 'AVOID SPRAYING', 'UNAVAILABLE')
    and localized reason text based on real meteorological parameters and selected language.
    """
    lang = str(language).lower().strip()
    if lang not in SPRAYING_WINDOW_TEXT_I18N:
        lang = 'en'
    texts = SPRAYING_WINDOW_TEXT_I18N[lang]

    if not weather_context or not isinstance(weather_context, dict):
        return "UNAVAILABLE", texts['unavailable']

    try:
        temp = float(weather_context.get("temp", 0) or 0)
    except Exception:
        temp = 25.0

    try:
        wind = float(weather_context.get("wind_speed", 0) or weather_context.get("wind", 0) or 0)
    except Exception:
        wind = 5.0

    try:
        rain_prob = int(weather_context.get("rain_prob", 0) or weather_context.get("rain_probability", 0) or 0)
    except Exception:
        rain_prob = 0

    try:
        rain_amount = float(weather_context.get("rain_amount", 0) or 0)
    except Exception:
        rain_amount = 0.0

    condition = str(weather_context.get("condition", "")).lower()

    if rain_prob >= 50 or rain_amount > 1.0 or any(w in condition for w in ["rain", "thunder", "storm", "shower", "drizzle"]):
        return "AVOID SPRAYING", texts['avoid_rain']
    elif wind >= 24.0:
        return "AVOID SPRAYING", texts['avoid_wind']
    elif temp >= 38.0:
        return "CAUTION", texts['caution_temp']
    elif wind >= 16.0 or rain_prob >= 30:
        return "CAUTION", texts['caution_wind_rain']
    else:
        return "GOOD SPRAYING WINDOW", texts['good_window']

def build_structured_treatment(
    crop: str,
    disease: str,
    severity: str,
    risk_level: str,
    language: str = 'en',
    weather_context: Optional[Dict[str, Any]] = None,
    raw_treatment: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Builds a robust, structured, verified treatment plan adhering strictly to agronomic safety
    and fully localized in the farmer's selected language.
    Healthy crops receive zero chemicals.
    """
    lang = str(language).lower().strip()
    if lang not in MANDATORY_SAFETY_PRECAUTIONS_I18N:
        lang = 'en'

    is_healthy = "health" in disease.lower() or severity == "HEALTHY" or "none" in disease.lower() or "no disease" in disease.lower() or "ஆரோக்கிய" in disease.lower() or "स्वस्थ" in disease.lower() or "ఆరోగ్య" in disease.lower()
    spraying_window, spraying_reason = evaluate_spraying_window(weather_context, language=lang)

    healthy_defs = HEALTHY_TREATMENT_I18N.get(lang, HEALTHY_TREATMENT_I18N['en'])
    disease_fallback = DISEASE_FALLBACK_I18N.get(lang, DISEASE_FALLBACK_I18N['en'])
    safety_precautions = list(MANDATORY_SAFETY_PRECAUTIONS_I18N.get(lang, MANDATORY_SAFETY_PRECAUTIONS_I18N['en']))

    if is_healthy:
        healthy_name = HEALTHY_DISEASE_NAMES_I18N.get(lang, "Healthy")
        return {
            "disease": healthy_name,
            "crop": localize_crop_name(crop, lang) or crop or "Crop",
            "severity": "HEALTHY",
            "risk_level": "NO RISK",
            "treatment_category": "PREVENTIVE_CARE",
            "immediate_action": healthy_defs['immediate_action'],
            "treatment_objective": healthy_defs['treatment_objective'],
            "management": list(healthy_defs['management']),
            "medicine_guidance": [],
            "weather_precaution": healthy_defs['weather_precaution'],
            "spraying_window": spraying_window,
            "spraying_reason": spraying_reason,
            "safety_precautions": list(healthy_defs['safety_precautions']),
            "avoid": list(healthy_defs['avoid']),
            "rescan_recommended": False
        }

    # If Gemini returned valid structured treatment, sanitize and integrate it
    if raw_treatment and isinstance(raw_treatment, dict):
        immediate_action = str(raw_treatment.get("immediate_action", "")).strip()
        treatment_objective = str(raw_treatment.get("treatment_objective", "")).strip()
        treatment_category = str(raw_treatment.get("treatment_category", "CONFIRMED_TREATMENT")).strip().upper()
        
        management = raw_treatment.get("management")
        if not isinstance(management, list) or not management:
            management = list(disease_fallback['management'])
        else:
            management = [str(m).strip() for m in management if str(m).strip()]

        med_list = raw_treatment.get("medicine_guidance")
        cleaned_meds = []
        if isinstance(med_list, list):
            for m in med_list:
                if isinstance(m, dict) and m.get("active_ingredient"):
                    raw_purp = str(m.get("purpose", "")).strip()
                    raw_app = str(m.get("application_method", "")).strip()
                    raw_tim = str(m.get("timing", "")).strip()
                    cleaned_meds.append({
                        "active_ingredient": str(m.get("active_ingredient", "")).strip(),
                        "purpose": localize_purpose(raw_purp, lang),
                        "application_method": localize_application_method(raw_app, lang),
                        "timing": localize_timing(raw_tim, lang)
                    })

        weather_precaution = str(raw_treatment.get("weather_precaution", "")).strip()
        if not weather_precaution:
            weather_precaution = disease_fallback['weather_precaution']

        avoid = raw_treatment.get("avoid")
        if not isinstance(avoid, list) or not avoid:
            avoid = list(disease_fallback['avoid'])
        else:
            avoid = [str(a).strip() for a in avoid if str(a).strip()]

        gemini_safety = raw_treatment.get("safety_precautions")
        if isinstance(gemini_safety, list) and len(gemini_safety) >= 2:
            safety_list = [str(s).strip() for s in gemini_safety if str(s).strip()]
        else:
            safety_list = safety_precautions

        rescan_rec = raw_treatment.get("rescan_recommended")
        if not isinstance(rescan_rec, bool):
            rescan_rec = severity in ("MODERATE", "SEVERE")

        if not immediate_action:
            immediate_action = disease_fallback['immediate_action']
        if not treatment_objective:
            treatment_objective = disease_fallback['treatment_objective']

        return {
            "disease": disease,
            "crop": localize_crop_name(crop, lang) or crop,
            "severity": severity,
            "risk_level": risk_level,
            "treatment_category": treatment_category if treatment_category in ("CONFIRMED_TREATMENT", "GENERAL_MANAGEMENT", "EXPERT_CONSULTATION") else "CONFIRMED_TREATMENT",
            "immediate_action": immediate_action,
            "treatment_objective": treatment_objective,
            "management": management,
            "medicine_guidance": cleaned_meds,
            "weather_precaution": weather_precaution,
            "spraying_window": spraying_window,
            "spraying_reason": spraying_reason,
            "safety_precautions": safety_list,
            "avoid": avoid,
            "rescan_recommended": rescan_rec
        }

    # Default fallback structured plan if Gemini returned text or failed
    return {
        "disease": disease,
        "crop": localize_crop_name(crop, lang) or crop,
        "severity": severity,
        "risk_level": risk_level,
        "treatment_category": "GENERAL_MANAGEMENT" if severity == "MILD" else ("CONFIRMED_TREATMENT" if severity == "MODERATE" else "EXPERT_CONSULTATION"),
        "immediate_action": disease_fallback['immediate_action'],
        "treatment_objective": disease_fallback['treatment_objective'],
        "management": list(disease_fallback['management']),
        "medicine_guidance": [],
        "weather_precaution": disease_fallback['weather_precaution'],
        "spraying_window": spraying_window,
        "spraying_reason": spraying_reason,
        "safety_precautions": safety_precautions,
        "avoid": list(disease_fallback['avoid']),
        "rescan_recommended": severity in ("MODERATE", "SEVERE")
    }

build_structured_treatment_plan = build_structured_treatment

