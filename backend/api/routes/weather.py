@weather_bp.route('/api/weather', methods=['GET'])
@login_required
def get_weather():
    state = current_user.location or 'Punjab'
    lang = current_user.language or 'en'
    
    # Clean up state representation if formatted weirdly
    state_key = state.strip()
    
    adv_data = STATE_ADVISORIES.get(state_key, DEFAULT_ADVISORY)
    
    # Generate realistic dynamic temp/humidity
    min_t, max_t = adv_data['temp']
    current_temp = random.randint(min_t, max_t)
    
    min_h, max_h = adv_data['humidity']
    current_humidity = random.randint(min_h, max_h)
    
    weather_cond = adv_data['conditions'].get(lang, adv_data['conditions']['en'])
    crop_info = adv_data['crop'].get(lang, adv_data['crop']['en'])
    advisory_msg = adv_data['advisory'].get(lang, adv_data['advisory']['en'])
    
    return jsonify({
        'state': state_key,
        'temperature': current_temp,
        'humidity': current_humidity,
        'condition': weather_cond,
        'primary_crop': crop_info,
        'advisory': advisory_msg,
        'wind_speed': random.randint(5, 18),
        'rainfall_probability': random.choice([10, 20, 40, 70, 90]) if 'Rain' in adv_data['conditions']['en'] or 'Thunderstorm' in adv_data['conditions']['en'] else random.randint(0, 15)
    }), 200
